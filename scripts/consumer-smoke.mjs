/**
 * Generates the Next.js consumer smoke page from the component manifest (`docs/ai/components.json`).
 *
 * Every component whose source carries no `"use client"` is rendered in a Server Component (`app/smoke/page.jsx`), every
 * other one through a client boundary (`app/smoke/boundary.jsx`). `scripts/check-next-consumer.mjs` then asserts each
 * generated section is in the server HTML. A component with required props that can be neither derived from the manifest
 * nor found in `scripts/consumer-smoke-fixtures.mjs` is an error, and so is a fixture for an export that does not exist.
 *
 *   node scripts/consumer-smoke.mjs           write the generated files
 *   node scripts/consumer-smoke.mjs --check   fail when they are missing, stale or a component has no props
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FIXTURES } from "./consumer-smoke-fixtures.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = "docs/ai/components.json";
const OUT_DIR = "tests/consumer/next-app/app/smoke";
const HEADER = `// Generated by scripts/consumer-smoke.mjs from ${MANIFEST}. Do not edit: run npm run build:consumer-smoke.\n`;

const SOURCE_FILE = /\.(ts|tsx|js|jsx)$/;
const NOT_SHIPPED = /\.(test|stories)\.[jt]sx?$/;

/** True when the first statement of a module is the `"use client"` directive (leading comments allowed; no regex, so no backtracking). */
function hasUseClientDirective(source) {
  let rest = source.trimStart();
  for (;;) {
    if (rest.startsWith("//")) {
      const end = rest.indexOf("\n");
      rest = end === -1 ? "" : rest.slice(end).trimStart();
    } else if (rest.startsWith("/*")) {
      const end = rest.indexOf("*/");
      rest = end === -1 ? "" : rest.slice(end + 2).trimStart();
    } else break;
  }
  return rest.startsWith('"use client"') || rest.startsWith("'use client'");
}

/** True when any shipped source file of the manifest entry starts with the `"use client"` directive. */
export function isClientEntry(entry, root = ROOT) {
  const dir = path.join(root, entry.source);
  return readdirSync(dir)
    .filter((file) => SOURCE_FILE.test(file) && !NOT_SHIPPED.test(file))
    .some((file) => hasUseClientDirective(readFileSync(path.join(dir, file), "utf8")));
}

const FUNCTION_TYPE = /^\(.*\)\s*=>\s*(.+)$/s;

/** Splits a type at its top-level `|`, ignoring bars inside brackets, parentheses, generics and quotes. */
function unionMembers(type) {
  const members = [];
  let depth = 0;
  let quote = "";
  let start = 0;
  for (let i = 0; i < type.length; i += 1) {
    const char = type[i];
    if (quote) {
      if (char === quote) quote = "";
    } else if (char === '"' || char === "'") quote = char;
    else if ("([{<".includes(char)) depth += 1;
    else if (")]}>".includes(char) && !(char === ">" && type[i - 1] === "=")) depth -= 1;
    else if (char === "|" && depth === 0) {
      members.push(type.slice(start, i).trim());
      start = i + 1;
    }
  }
  members.push(type.slice(start).trim());
  return members;
}

/** A minimal JavaScript expression for a manifest type, or undefined when none can be derived. */
export function deriveValue(type, { client }) {
  for (const member of unionMembers(type.trim())) {
    if (member === "string" || member === "ReactNode") return `"x"`;
    if (member === "number") return "1";
    if (member === "boolean") return "false";
    if (/^"[^"]*"$/.test(member)) return member;
    // A callback can only be passed to a client component, and only a void one has an obvious body.
    const fn = FUNCTION_TYPE.exec(member);
    if (client && fn && fn[1].trim() === "void") return "() => {}";
  }
  return undefined;
}

/** The props expression map of one export, or the names of the required props nothing provides. */
function propsFor(exported, { client, fixtures }) {
  const fixture = fixtures[exported.name] ?? {};
  const props = {};
  const missing = [];
  for (const [name, expression] of Object.entries(fixture)) props[name] = expression;
  for (const prop of exported.props ?? []) {
    if (!prop.required || prop.name in props) continue;
    const value = deriveValue(prop.type, { client });
    if (value === undefined) missing.push(prop.name);
    else props[prop.name] = value;
  }
  return { props, missing };
}

/**
 * A server-safe export that requires a callback is only usable from a client component (a Server Component cannot pass a
 * function to the element that calls it), so the smoke renders it through the boundary.
 */
const needsCallback = (exported) =>
  (exported.props ?? []).some(
    (prop) => prop.required && unionMembers(prop.type).some((m) => FUNCTION_TYPE.test(m)),
  );

const identifier = (...parts) => parts.join("_").replace(/[^A-Za-z0-9_$]/g, "_");

/**
 * Plans the smoke page from the manifest. `isClient` decides the side of an entry. Returns the sections, grouped by side,
 * and the problems that make the plan unusable. The first component export that carries the entry's name (else the first
 * component export) is always rendered (through the boundary when it needs a callback); the other component exports of a server-safe entry are rendered when their
 * required props can be provided, and skipped otherwise (they are listed in `skipped`).
 */
export function planSmoke(manifest, { isClient = isClientEntry, fixtures = FIXTURES } = {}) {
  const sections = { server: [], client: [] };
  const problems = [];
  const skipped = [];
  const known = new Set();

  for (const entry of manifest.components) {
    const client = isClient(entry);
    const side = client ? "client" : "server";
    const components = entry.exports.filter((exported) => exported.kind === "component");
    for (const exported of entry.exports) known.add(exported.name);

    if (components.length === 0) {
      // Hooks, helpers and type-only modules: the import must resolve and the module must evaluate.
      sections[side].push({
        id: entry.name,
        subpath: entry.entry.subpath,
        namespace: identifier(entry.name),
      });
      continue;
    }

    const primary = components.find((exported) => exported.name === entry.name) ?? components[0];
    const rendered = client ? [primary] : [primary, ...components.filter((exported) => exported !== primary)];
    for (const exported of rendered) {
      const exportSide = client || needsCallback(exported) ? "client" : "server";
      const { props, missing } = propsFor(exported, { client: exportSide === "client", fixtures });
      if (missing.length > 0 && exported === primary) {
        problems.push(
          `${exported.name} (${entry.name}): no props for required ${missing.join(", ")}; add a fixture to scripts/consumer-smoke-fixtures.mjs`,
        );
        continue;
      }
      if (missing.length > 0) {
        skipped.push(`${entry.name}/${exported.name}`);
        continue;
      }
      sections[exportSide].push({
        id:
          exported === primary && exported.name === entry.name
            ? entry.name
            : `${entry.name}/${exported.name}`,
        subpath: entry.entry.subpath,
        name: exported.name,
        alias: identifier(entry.name, exported.name),
        props,
      });
    }
  }

  for (const name of Object.keys(fixtures)) {
    if (!known.has(name)) problems.push(`Fixture ${name} matches no export in the manifest; remove it`);
  }
  return { sections, problems, skipped };
}

function importLines(sections) {
  const bySubpath = new Map();
  for (const section of sections) {
    if (!bySubpath.has(section.subpath)) bySubpath.set(section.subpath, { names: [], namespaces: [] });
    const imports = bySubpath.get(section.subpath);
    if (section.namespace) imports.namespaces.push(section.namespace);
    else imports.names.push(`${section.name} as ${section.alias}`);
  }
  const lines = [];
  for (const [subpath, { names, namespaces }] of bySubpath) {
    if (names.length > 0) lines.push(`import { ${names.join(", ")} } from "${subpath}";`);
    for (const namespace of namespaces) lines.push(`import * as ${namespace} from "${subpath}";`);
  }
  return lines;
}

function sectionElement(section) {
  if (section.namespace) {
    return `<section data-smoke="${section.id}" data-exports={Object.keys(${section.namespace}).length} />`;
  }
  const { children, ...rest } = section.props;
  const attributes = Object.entries(rest)
    .map(([name, expression]) => ` ${name}={${expression}}`)
    .join("");
  const inner =
    children === undefined
      ? `<${section.alias}${attributes} />`
      : `<${section.alias}${attributes}>{${children}}</${section.alias}>`;
  return `<section data-smoke="${section.id}">${inner}</section>`;
}

/** Renders the generated files as a Map of repository-relative path to content. */
export function renderSmoke(plan) {
  const skippedNote =
    plan.skipped.length > 0
      ? `// Exports left out because their required props have no derivation or fixture: ${plan.skipped.join(", ")}.\n`
      : "";
  const boundary = [
    HEADER,
    `"use client";\n`,
    ...importLines(plan.sections.client).map((line) => `${line}\n`),
    `\nexport default function ClientSmoke() {\n  return (\n    <>\n${plan.sections.client
      .map((section) => `      ${sectionElement(section)}\n`)
      .join("")}    </>\n  );\n}\n`,
  ].join("");
  const page = [
    HEADER,
    skippedNote,
    ...importLines(plan.sections.server).map((line) => `${line}\n`),
    `import ClientSmoke from "./boundary";\n`,
    `\nexport const metadata = { title: "Lufia server component smoke" };\n`,
    `\n// A Server Component: it renders every manifest component without "use client", then the client ones through the boundary.\n`,
    `export default function SmokePage() {\n  return (\n    <main>\n      <h1>Lufia server component smoke</h1>\n${plan.sections.server
      .map((section) => `      ${sectionElement(section)}\n`)
      .join("")}      <ClientSmoke />\n    </main>\n  );\n}\n`,
  ].join("");
  return new Map([
    [`${OUT_DIR}/page.jsx`, page],
    [`${OUT_DIR}/boundary.jsx`, boundary],
  ]);
}

export function loadManifest(root = ROOT) {
  return JSON.parse(readFileSync(path.join(root, MANIFEST), "utf8"));
}

/** Every section id the page must contain, server and client. */
export function smokeIds(plan) {
  return [...plan.sections.server, ...plan.sections.client].map((section) => section.id);
}

/** Problems with the generated files on disk: the plan's own, and each file missing or different from a fresh render. */
export function checkSmoke(root = ROOT) {
  const plan = planSmoke(loadManifest(root), { isClient: (entry) => isClientEntry(entry, root) });
  const problems = [...plan.problems];
  if (problems.length > 0) return problems;
  for (const [file, content] of renderSmoke(plan)) {
    const target = path.join(root, file);
    if (!existsSync(target)) problems.push(`${file} is missing; run npm run build:consumer-smoke`);
    else if (readFileSync(target, "utf8") !== content)
      problems.push(`${file} is out of date; run npm run build:consumer-smoke`);
  }
  return problems;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const problems = checkSmoke();
    if (problems.length > 0) {
      for (const problem of problems) console.error(`verify:consumer-smoke: ${problem}`);
      process.exit(1);
    }
    console.log("verify:consumer-smoke ok");
  } else {
    const plan = planSmoke(loadManifest());
    if (plan.problems.length > 0) {
      for (const problem of plan.problems) console.error(`consumer-smoke: ${problem}`);
      process.exit(1);
    }
    mkdirSync(path.join(ROOT, OUT_DIR), { recursive: true });
    for (const [file, content] of renderSmoke(plan)) writeFileSync(path.join(ROOT, file), content);
    console.log(
      `consumer-smoke: ${plan.sections.server.length} server and ${plan.sections.client.length} client sections written`,
    );
  }
}
