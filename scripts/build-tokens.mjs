// Builds CSS custom properties, a typed TS map and a docs JSON from the DTCG sources in tokens/.
import { mkdirSync, writeFileSync } from "node:fs";
import StyleDictionary from "style-dictionary";

const THEMES = ["default", "example-brand"];
const MODES = ["light", "dark"];
const PREFIX = "lufia";

const isPrimitive = (token) => token.path[0] === "core";

async function resolve(sources, platformName = "css") {
  const sd = new StyleDictionary({
    usesDtcg: true,
    log: { verbosity: "silent", warnings: "warn" },
    source: sources,
    platforms: {
      [platformName]: { transformGroup: "css", prefix: PREFIX, buildPath: "dist/" },
    },
  });
  return (await sd.getPlatformTokens(platformName)).allTokens;
}

const cssValue = (token) => String(token.$value ?? token.value);
const varName = (token) => `--${token.name}`;
const declarations = (tokens, indent = "  ") =>
  tokens.map((t) => `${indent}${varName(t)}: ${cssValue(t)};`).join("\n");

const FORCED = {
  "color-bg-canvas": "Canvas",
  "color-bg-surface": "Canvas",
  "color-bg-surface-raised": "Canvas",
  "color-bg-surface-solid": "Canvas",
  "color-bg-field": "Field",
  "color-bg-field-autofill": "Field",
  "color-text-default": "CanvasText",
  "color-text-muted": "CanvasText",
  "color-text-subtle": "CanvasText",
  "color-text-on-accent": "HighlightText",
  "color-text-accent": "LinkText",
  "color-border-subtle": "CanvasText",
  "color-border-strong": "CanvasText",
  "color-accent-default": "Highlight",
  "color-accent-hover": "Highlight",
  "color-accent-subtle": "Canvas",
  "color-accent-border": "Highlight",
  "color-focus-ring": "Highlight",
  "color-status-success-fg": "CanvasText",
  "color-status-success-bg": "Canvas",
  "color-status-success-border": "CanvasText",
  "color-status-warning-fg": "CanvasText",
  "color-status-warning-bg": "Canvas",
  "color-status-warning-border": "CanvasText",
  "color-status-danger-fg": "CanvasText",
  "color-status-danger-bg": "Canvas",
  "color-status-danger-border": "CanvasText",
  "color-status-danger-solid": "Highlight",
  "color-status-danger-on-solid": "HighlightText",
  "color-status-ai-fg": "CanvasText",
  "color-status-ai-bg": "Canvas",
  "color-status-ai-border": "CanvasText",
  "color-status-neutral-fg": "CanvasText",
  "color-status-neutral-bg": "Canvas",
};

mkdirSync("dist/themes", { recursive: true });
mkdirSync("dist/tokens", { recursive: true });
mkdirSync("src/tokens/generated", { recursive: true });

const primitives = ["tokens/primitive/*.tokens.json"];
const shared = [...primitives, "tokens/semantic/shared.tokens.json"];

// ---- Shared (mode independent) tokens -> dist/tokens.css
const sharedTokens = (await resolve(shared)).filter((t) => !isPrimitive(t));
const durations = sharedTokens.filter((t) => t.name.startsWith(`${PREFIX}-motion-duration-`));
const distances = sharedTokens.filter((t) => t.name.startsWith(`${PREFIX}-motion-distance-`));
const banner = "/* Generated by scripts/build-tokens.mjs from tokens/*.tokens.json. Do not edit. */\n";
const tokensCss =
  `${banner}:root {\n${declarations(sharedTokens)}\n}\n\n` +
  `/* Reduced motion: durations and travel distances collapse; components keep their end state.\n` +
  `   Durations stay at 0.01ms (not 0) so animationend and transitionend still fire. */\n` +
  `@media (prefers-reduced-motion: reduce) {\n  :root {\n${[
    ...durations.map((t) => `    ${varName(t)}: 0.01ms;`),
    ...distances.map((t) => `    ${varName(t)}: 0rem;`),
  ].join("\n")}\n  }\n}\n`;
writeFileSync("dist/tokens.css", tokensCss);

// ---- Themes -> dist/themes/<theme>.css
const docs = { shared: {}, primitives: {}, themes: {} };
const toDoc = (t) => ({
  name: t.name,
  path: t.path,
  value: cssValue(t),
  type: t.$type ?? t.type,
  description: t.$description ?? t.comment ?? "",
  original: typeof t.original?.$value === "string" ? t.original.$value : undefined,
});
for (const t of sharedTokens) docs.shared[t.path.join(".")] = toDoc(t);
for (const t of (await resolve(primitives)).filter(isPrimitive)) docs.primitives[t.path.join(".")] = toDoc(t);

for (const theme of THEMES) {
  const blocks = {};
  docs.themes[theme] = {};
  for (const mode of MODES) {
    const tokens = (await resolve([...primitives, `tokens/themes/${theme}.${mode}.tokens.json`])).filter(
      (t) => !isPrimitive(t),
    );
    blocks[mode] = tokens;
    docs.themes[theme][mode] = Object.fromEntries(tokens.map((t) => [t.path.join("."), toDoc(t)]));
  }
  // The default theme also applies when no theme is named; named themes need data-lufia-theme.
  const named = `[data-lufia-theme="${theme}"]`;
  const light = theme === "default" ? `:root:not([data-lufia-theme]),\n${named}` : named;
  const dark =
    theme === "default"
      ? `:root:not([data-lufia-theme])[data-lufia-mode="dark"],\n${named}[data-lufia-mode="dark"]`
      : `${named}[data-lufia-mode="dark"]`;
  const auto =
    theme === "default"
      ? `:root:not([data-lufia-theme]):not([data-lufia-mode]),\n    ${named}:not([data-lufia-mode])`
      : `${named}:not([data-lufia-mode])`;
  const forced = blocks.light
    .filter((t) => FORCED[t.name.replace(`${PREFIX}-`, "")])
    .map((t) => `    ${varName(t)}: ${FORCED[t.name.replace(`${PREFIX}-`, "")]} !important;`)
    .join("\n");
  const css =
    `${banner}/* Theme: ${theme}. Optionally set data-lufia-theme="${theme}" on <html>${theme === "default" ? " (the default applies without it)" : ""}; force a mode with data-lufia-mode="light|dark", or omit it to follow prefers-color-scheme. */\n` +
    `${light} {\n  color-scheme: light;\n${declarations(blocks.light)}\n}\n\n` +
    `${dark} {\n  color-scheme: dark;\n${declarations(blocks.dark)}\n}\n\n` +
    `@media (prefers-color-scheme: dark) {\n  ${auto} {\n    color-scheme: dark;\n${declarations(blocks.dark, "    ")}\n  }\n}\n\n` +
    `/* High contrast: system colours override theme colours. */\n@media (forced-colors: active) {\n  :root,\n  [data-lufia-theme] {\n${forced}\n  }\n}\n`;
  writeFileSync(`dist/themes/${theme}.css`, css);
}

// ---- Docs JSON + typed TS map
writeFileSync("dist/tokens.json", JSON.stringify(docs, null, 2) + "\n");

const nested = {};
const names = [];
for (const t of [
  ...sharedTokens,
  ...(await resolve([...primitives, "tokens/themes/default.light.tokens.json"])).filter(
    (t) => !isPrimitive(t),
  ),
]) {
  let node = nested;
  t.path.slice(0, -1).forEach((p) => (node = node[p] ??= {}));
  node[t.path.at(-1)] = `var(${varName(t)})`;
  names.push(varName(t));
}
const ts =
  `// Generated by scripts/build-tokens.mjs. Do not edit.\n` +
  `/** Every \`--lufia-*\` custom property the package defines. */\n` +
  `export type TokenName = ${names.map((n) => JSON.stringify(n)).join(" | ")};\n\n` +
  `/** Nested map of token path to a \`var(--lufia-*)\` reference. */\n` +
  `export const tokens = ${JSON.stringify(nested, null, 2)} as const;\n`;
writeFileSync("src/tokens/generated/tokens.ts", ts);
console.log(`tokens: ${names.length} custom properties, ${THEMES.length} themes x ${MODES.length} modes`);
